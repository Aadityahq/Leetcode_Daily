
class Solution {
    public int maximumSaleItems(int[][] items, int budget) {
        int n = items.length;
        int maxFactor = 1500;

        // Step 1: Count frequency of every factor
        int[] freq = new int[maxFactor + 1];

        for (int[] item : items) {
            freq[item[0]]++;
        }

        // Step 2: Calculate how many items each factor divides
        int[] count = new int[maxFactor + 1];

        for (int d = 1; d <= maxFactor; d++) {
            for (int multiple = d;
                 multiple <= maxFactor;
                 multiple += d) {

                count[d] += freq[multiple];
            }
        }

        // Step 3: DP initialization
        int NEG = -1_000_000;

        int[] dp = new int[budget + 1];
        java.util.Arrays.fill(dp, NEG);

        dp[0] = 0;

        // Step 4: Process every item
        for (int[] item : items) {

            int factor = item[0];
            int price = item[1];

            // Free items generated by this item
            int free = count[factor] - 1;

            // Preserve previous DP states
            int[] prev = dp.clone();

            // Step 5: Process each remainder group
            for (int r = 0; r < price && r <= budget; r++) {

                int best = NEG;

                int t = 0;

                for (int b = r; b <= budget; b += price) {

                    // Include previous position in prefix maximum
                    if (t > 0) {

                        int previous = prev[b - price];

                        if (previous != NEG) {
                            best = Math.max(
                                best,
                                previous - (t - 1)
                            );
                        }
                    }

                    // Option 1: Don't purchase this item
                    dp[b] = prev[b];

                    // Option 2: Purchase one or more copies
                    if (best != NEG) {

                        int candidate = free + t + best;

                        dp[b] = Math.max(
                            dp[b],
                            candidate
                        );
                    }

                    t++;
                }
            }
        }

        // Step 6: Find maximum items within budget
        int answer = 0;

        for (int b = 0; b <= budget; b++) {
            answer = Math.max(answer, dp[b]);
        }

        return answer;
    }
}
